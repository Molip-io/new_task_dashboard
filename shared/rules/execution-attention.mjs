export function classifyExecutionAttention(value) {
  const text = String(value || '').replace(/\s+/g, ' ').trim();
  if (!text || RESOLVED_PATTERN.test(text)) return null;
  const rule = ATTENTION_RULES.find(candidate => candidate.pattern.test(text));
  return rule ? { type: rule.type, action: rule.action } : null;
}
